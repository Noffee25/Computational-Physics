      PROGRAM RNDTEST
      USE RNGLIB
C
C ******************************************************************
C *** DEEP HISTOGRAM TEST OF PSEUDORANDOM NUMBER GENERATORS
C *** (REWRITE OF THE COURSE PROGRAM RNDTEST, PHYS 25000 PROJECT 1)
C ******************************************************************
C ***
C *** THE COURSE PROGRAM FILLED PRECIS BINS WITH 100*PRECIS RANDOM
C *** NUMBERS AND WROTE EVERY BIN TO A FILE. AT 1E7 OR 1E8 BINS THAT
C *** FILE IS HUGE AND HARD TO JUDGE BY EYE, SO THIS VERSION REDUCES
C *** THE HISTOGRAM TO A FEW NUMBERS WHOSE NULL DISTRIBUTION IS KNOWN
C *** (N DRAWS OF A TRUE UNIFORM VARIATE INTO B EQUAL BINS GIVE A
C *** MULTINOMIAL HISTOGRAM, ESSENTIALLY POISSON(N/B) PER BIN):
C ***
C ***   NEMPTY   NUMBER OF BINS THAT RECEIVED NO HITS
C ***   AVERAG   MEAN HITS PER BIN, LAMBDA = N/B (EXACT)
C ***   VAR      SAMPLE VARIANCE OF THE BIN COUNTS (DIVISOR B-1)
C ***   D        DISPERSION INDEX VAR/AVERAG.  IDEAL VALUE 1.
C ***            D < 1 : BINS TOO EVEN  (E.G. PERIOD EXHAUSTION)
C ***            D > 1 : BINS TOO UNEVEN (E.G. MISSING VALUES)
C ***   CHI2     PEARSON CHI-SQUARE SUM (N_J-LAMBDA)**2/LAMBDA
C ***            = (B-1)*D, WITH B-1 DEGREES OF FREEDOM
C ***   Z        (CHI2-(B-1))/SQRT(2(B-1)(1-1/N)), THE EXACT
C ***            MULTINOMIAL MEAN AND VARIANCE OF CHI2
C ***   N4LO/HI  BINS MORE THAN CL STANDARD ERRORS SQRT(LAMBDA)
C ***            BELOW/ABOVE THE MEAN (THE COURSE CRITERION)
C ***   E4LO/HI  EXPECTED NUMBER OF SUCH BINS (EXACT BINOMIAL TAILS)
C ***   COUNT-OF-COUNTS TABLE: HOW MANY BINS RECEIVED EXACTLY K HITS
C ***   PROFILE (OPTIONAL): MEAN AND D INSIDE NREG CONSECUTIVE BLOCKS
C ***            OF BINS, TO LOCATE WHERE IN (0,1) A PROBLEM SITS
C ***
C *** USAGE:  ./rnd_test_claude [SUMMARY] [COCFILE] [PROFFILE] < JOBS
C ***   EACH LINE OF THE JOB FILE (LIST DIRECTED) IS
C ***      IGEN IPREC NBINS NDRAW ISEED ICOC NREG TAG
C ***   IGEN  : 1 RANDU   2 RANDM   3 RAND   4 MINSTD  5 R250
C ***           6 RANNUM  7 MT19937 8 MIDSQ  9 LOGISTIC (SEE RNGLIB)
C ***   IPREC : 8 = DOUBLE PRECISION, 4 = NUMBER STORED IN A REAL*4
C ***   NBINS : NUMBER OF BINS B (THE "DEPTH" OF THE TEST)
C ***   NDRAW : NUMBER OF RANDOM NUMBERS N
C ***   ISEED : SEED
C ***   ICOC  : 1 = WRITE THE COUNT-OF-COUNTS TABLE, 0 = DO NOT
C ***   NREG  : NUMBER OF PROFILE BLOCKS (0 = NO PROFILE)
C ***   TAG   : SHORT LABEL WITHOUT BLANKS
C *** ALL OUTPUT FILES ARE APPENDED TO, ONE BLOCK PER JOB.
C ***
C *** COMPILE:  gfortran -O2 -c rnglib.f90
C ***           gfortran -O2 rnd_test_claude.f rnglib.o -o rnd_test
C ******************************************************************
C
      IMPLICIT NONE
      INTEGER, ALLOCATABLE :: IBIN(:)
      INTEGER*8, ALLOCATABLE :: KTAB(:)
      INTEGER*8 NDRAW, ISEED, I, NEMPTY, N4LO, N4HI, NOVER, S1
      INTEGER*8 KLO4, KHI4
      INTEGER IGEN, IPREC, NB, ICOC, NREG, J, INDEX, MINC, MAXC
      INTEGER K, K0, LTAB, IR, MB, J1, J2, IOS, NJOB, NARG
      INTEGER*8 T0, T1, TRATE
      DOUBLE PRECISION X, DB, AVERAG, STDERR, CL, DEV, S2, VAR, D
      DOUBLE PRECISION CHI2, Z, E4LO, E4HI, P, SECS, RM, RV
      DOUBLE PRECISION BINSUM
      CHARACTER*40 TAG
      CHARACTER*200 FSUM, FCOC, FPRO
      PARAMETER (LTAB = 2000000)
C
C *** CHOOSE A REASONABLE CONFIDENCE LEVEL TO CALL A BIN "ANOMALOUS"
      CL = 4.D0
C
C *** OUTPUT FILE NAMES FROM THE COMMAND LINE (OR DEFAULTS)
      FSUM = 'hist_summary.out'
      FCOC = 'hist_coc.out'
      FPRO = 'hist_prof.out'
      NARG = COMMAND_ARGUMENT_COUNT()
      IF (NARG.GE.1) CALL GET_COMMAND_ARGUMENT(1,FSUM)
      IF (NARG.GE.2) CALL GET_COMMAND_ARGUMENT(2,FCOC)
      IF (NARG.GE.3) CALL GET_COMMAND_ARGUMENT(3,FPRO)
      OPEN (UNIT=1,FILE=FSUM,STATUS='UNKNOWN',POSITION='APPEND')
      OPEN (UNIT=2,FILE=FCOC,STATUS='UNKNOWN',POSITION='APPEND')
      OPEN (UNIT=3,FILE=FPRO,STATUS='UNKNOWN',POSITION='APPEND')
      ALLOCATE(KTAB(0:LTAB-1))
      NJOB = 0
C
C *** LOOP OVER JOBS ***********************************************
  100 CONTINUE
      READ (5,*,IOSTAT=IOS) IGEN,IPREC,NB,NDRAW,ISEED,ICOC,NREG,TAG
      IF (IOS.NE.0) GOTO 900
      IF (IGEN.LT.1 .OR. IGEN.GT.NGEN) STOP 'BAD GENERATOR ID'
      IF (NB.LT.2) STOP 'NEED AT LEAST 2 BINS'
      IF (NDRAW.GT.2147483647_8) STOP 'NDRAW TOO LARGE FOR BINS'
      NJOB = NJOB + 1
      CALL SYSTEM_CLOCK(T0,TRATE)
C
C *** INITIALIZE ARRAYS
      ALLOCATE(IBIN(NB))
      DO 35 J=1,NB
      IBIN(J)=0
   35 CONTINUE
C
C *** SEED THE GENERATOR, CHOOSE THE PRECISION OF THE STORED NUMBER
      RNG_SINGLE = (IPREC.EQ.4)
      CALL RNG_INIT(IGEN,ISEED)
      DB = DBLE(NB)
C
C *** FILL THE HISTOGRAM
      DO 14 I=1,NDRAW
      X = RNG_NEXT(IGEN)
      INDEX = INT(X*DB) + 1
C *** JUST IN CASE
      IF (INDEX.GT.NB) INDEX = NB
      IF (INDEX.LT.1) INDEX = 1
      IBIN(INDEX) = IBIN(INDEX) + 1
   14 CONTINUE
      RNG_SINGLE = .FALSE.
C
C *** NOW INSPECT YOUR BINS FOR STATISTICALLY-
C *** SIGNIFICANT DEVIATIONS FROM THE MEAN
      AVERAG = DBLE(NDRAW)/DB
      STDERR = SQRT(AVERAG)
      NEMPTY = 0
      N4LO = 0
      N4HI = 0
      S1 = 0
      S2 = 0.D0
      MINC = IBIN(1)
      MAXC = IBIN(1)
      DO 21 J=1,NB
      K = IBIN(J)
      S1 = S1 + K
      S2 = S2 + (DBLE(K)-AVERAG)**2
      IF (K.EQ.0) NEMPTY = NEMPTY + 1
      IF (K.LT.MINC) MINC = K
      IF (K.GT.MAXC) MAXC = K
      DEV = (DBLE(K)-AVERAG)/STDERR
      IF (DEV.LE.-CL) N4LO = N4LO + 1
      IF (DEV.GE.CL)  N4HI = N4HI + 1
   21 CONTINUE
      IF (S1.NE.NDRAW) STOP 'LOST DRAWS'
      VAR  = S2/DBLE(NB-1)
      D    = VAR/AVERAG
      CHI2 = S2/AVERAG
      Z    = (CHI2-DBLE(NB-1))/SQRT(2.D0*DBLE(NB-1)*
     &       (1.D0-1.D0/DBLE(NDRAW)))
C
C *** EXPECTED NUMBER OF "ANOMALOUS" BINS FOR A PERFECT GENERATOR:
C *** EACH BIN IS BINOMIAL(N,1/B); SUM ITS PMF OVER THE TWO TAILS
C *** DEV <= -CL  AND  DEV >= +CL.
      P = 1.D0/DB
      KLO4 = FLOOR(AVERAG - CL*STDERR)
      KHI4 = CEILING(AVERAG + CL*STDERR)
      IF (KLO4.GE.0) THEN
         E4LO = DB*BINSUM(NDRAW,P,KLO4,-1)
      ELSE
         E4LO = 0.D0
      END IF
      E4HI = DB*BINSUM(NDRAW,P,KHI4,+1)
      CALL SYSTEM_CLOCK(T1)
      SECS = DBLE(T1-T0)/DBLE(TRATE)
C
      WRITE(1,'(A,1X,A,1X,I1,1X,I12,1X,I10,1X,I11,1X,I10,
     &   3(1X,ES17.10),2(1X,ES16.8),2(1X,I10),2(1X,ES12.5),
     &   2(1X,I11),1X,F9.2)')
     &   TRIM(TAG),TRIM(GEN_NAME(IGEN)),IPREC,ISEED,NB,NDRAW,NEMPTY,
     &   AVERAG,VAR,D,CHI2,Z,N4LO,N4HI,E4LO,E4HI,MINC,MAXC,SECS
      FLUSH(1)
C
C *** COUNT-OF-COUNTS: KTAB(K-K0) = NUMBER OF BINS WITH K HITS.
C *** IF THE COUNTS SPAN MORE THAN LTAB VALUES, TABULATE 0..LTAB-1
C *** AND REPORT THE REST AS OVERFLOW (WRITTEN WITH K = -1).
      IF (ICOC.EQ.1) THEN
         IF (MAXC-MINC.LT.LTAB) THEN
            K0 = MINC
         ELSE
            K0 = 0
         END IF
         DO 40 K=0,LTAB-1
         KTAB(K) = 0
   40    CONTINUE
         NOVER = 0
         DO 41 J=1,NB
         K = IBIN(J) - K0
         IF (K.LT.LTAB) THEN
            KTAB(K) = KTAB(K) + 1
         ELSE
            NOVER = NOVER + 1
         END IF
   41    CONTINUE
         DO 42 K=0,LTAB-1
         IF (KTAB(K).GT.0) WRITE(2,'(A,1X,I11,1X,I11)')
     &      TRIM(TAG),K+K0,KTAB(K)
   42    CONTINUE
         IF (NOVER.GT.0) WRITE(2,'(A,1X,I11,1X,I11)')
     &      TRIM(TAG),-1,NOVER
         FLUSH(2)
      END IF
C
C *** PROFILE: SPLIT THE B BINS INTO NREG BLOCKS OF MB CONSECUTIVE
C *** BINS AND GIVE THE MEAN AND THE DISPERSION INDEX OF EACH BLOCK
      IF (NREG.GT.0 .AND. NREG.LE.NB) THEN
         MB = NB/NREG
         DO 50 IR=1,NREG
         J1 = (IR-1)*MB + 1
         J2 = J1 + MB - 1
         IF (IR.EQ.NREG) J2 = NB
         RM = 0.D0
         DO 51 J=J1,J2
         RM = RM + DBLE(IBIN(J))
   51    CONTINUE
         RM = RM/DBLE(J2-J1+1)
         RV = 0.D0
         DO 52 J=J1,J2
         RV = RV + (DBLE(IBIN(J))-RM)**2
   52    CONTINUE
         IF (J2.GT.J1) RV = RV/DBLE(J2-J1)
         WRITE(3,'(A,1X,I7,2(1X,F12.9),2(1X,ES16.8))')
     &      TRIM(TAG),IR,DBLE(J1-1)/DB,DBLE(J2)/DB,RM,RV/AVERAG
   50    CONTINUE
         FLUSH(3)
      END IF
C
      DEALLOCATE(IBIN)
      GOTO 100
C
  900 CONTINUE
      CLOSE(1)
      CLOSE(2)
      CLOSE(3)
      STOP
      END
C
C
C ******************************************************************
C *** SUM OF THE BINOMIAL(N,P) PROBABILITY MASS FUNCTION STARTING AT
C *** K = KSTART AND RUNNING UP (IDIR=+1) OR DOWN (IDIR=-1) UNTIL THE
C *** TERMS ARE NEGLIGIBLE. LOG-GAMMA AVOIDS OVERFLOW FOR HUGE N.
C ******************************************************************
      DOUBLE PRECISION FUNCTION BINSUM(N,P,KSTART,IDIR)
      IMPLICIT NONE
      INTEGER*8 N, KSTART, K
      INTEGER IDIR
      DOUBLE PRECISION P, ALQ, ALP, ALN, T, DN, DK
      ALP = LOG(P)
      IF (P.LT.1.D-4) THEN
         ALQ = -P*(1.D0+P*(0.5D0+P/3.D0))
      ELSE
         ALQ = LOG(1.D0-P)
      END IF
      DN = DBLE(N)
      ALN = LOG_GAMMA(DN+1.D0)
      BINSUM = 0.D0
      K = KSTART
   10 CONTINUE
      IF (K.LT.0 .OR. K.GT.N) RETURN
      DK = DBLE(K)
      T = EXP(ALN-LOG_GAMMA(DK+1.D0)-LOG_GAMMA(DN-DK+1.D0)
     &    +DK*ALP+(DN-DK)*ALQ)
      BINSUM = BINSUM + T
C *** STOP ONCE PAST THE MODE AND THE TERMS NO LONGER MATTER
      IF (T.LT.1.D-25*BINSUM .AND. ABS(DK-DN*P).GT.SQRT(DN*P)) RETURN
      IF (T.EQ.0.D0 .AND. ABS(DK-DN*P).GT.SQRT(DN*P)+1.D0) RETURN
      K = K + IDIR
      GOTO 10
      END
